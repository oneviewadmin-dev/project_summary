/// 이 프로젝트에 주차 보드를 띄우나.
bool projectBoardOn(String projectKey) {
  final k = projectKey.toLowerCase();
  for (final want in kProjectBoardOn) {
    if (want.endsWith('_') ? k.startsWith(want) : k == want) {
      return true;
    }
  }
  return false;
}

